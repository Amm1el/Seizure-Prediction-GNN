"""Ablation on synthetic EEG: Fusion vs single-model baselines.

Run with ``python -m seizure_gnn.ablation`` or ``python scripts/run_ablation.py``.

This is a smoke test that the pipeline runs end to end and that each model can learn
a deliberately learnable synthetic task. It is NOT a reproduction of the poster's
results, which were measured on a real EEG dataset with the original (unpublished) code.
"""

from __future__ import annotations

import argparse
import os
import time

import numpy as np

from .data import SequenceDataset, SyntheticEEG, apply_feature_scaler, build_window_graphs, fit_feature_scaler
from .models import FusionClassifier, GCNEncoder, SpatialOnly, TemporalOnly
from .train import evaluate, make_loader, pretrain_dgi, set_seed, split_by_recording, train_classifier

MODELS = [
    ("Fusion (DGI-pretrained GCN + TCN)", "fusion"),
    ("Fusion without DGI pretraining", "fusion_nodgi"),
    ("SpatialOnly (GCN on last window)", "spatial"),
    ("TemporalOnly (TCN on features, no graph)", "temporal"),
]


def build_model(kind: str, train_recs, n_features: int, n_channels: int, seed: int, dgi_epochs: int, batch_size: int = 64):
    set_seed(seed)
    if kind == "fusion":
        encoder = GCNEncoder(n_features, 32)
        pretrain_dgi(encoder, train_recs, epochs=dgi_epochs, batch_size=batch_size)
        return FusionClassifier(encoder, freeze_encoder=False)
    if kind == "fusion_nodgi":
        return FusionClassifier(GCNEncoder(n_features, 32), freeze_encoder=False)
    if kind == "spatial":
        return SpatialOnly(n_features, 32)
    if kind == "temporal":
        return TemporalOnly(n_features * n_channels, 32)
    raise ValueError(kind)


def run(
    seeds=(0, 1, 2),
    n_recordings: int = 12,
    epochs: int = 10,
    dgi_epochs: int = 5,
    seq_len: int = 6,
    horizon: int = 1,
    effect_strength: float = 0.5,
    batch_size: int = 64,
    out_path: str | None = "results/ablation_synthetic.md",
):
    """Train and test every model in ``MODELS`` on fresh synthetic data for each seed."""
    start = time.time()
    results = {kind: [] for _, kind in MODELS}
    for seed in seeds:
        gen = SyntheticEEG(n_channels=16, fs=128.0, effect_strength=effect_strength, seed=seed)
        recordings = [build_window_graphs(r, window_sec=2.0, stride_sec=1.0) for r in gen.generate_dataset(n_recordings)]
        train, val, test = split_by_recording(recordings, seed=seed)
        mean, std = fit_feature_scaler(train)
        train, val, test = (apply_feature_scaler(s, mean, std) for s in (train, val, test))
        train_set, val_set, test_set = (SequenceDataset(s, seq_len, horizon) for s in (train, val, test))
        n_channels, n_features = train[0].graphs[0].x.shape

        for _, kind in MODELS:
            model = build_model(kind, train, n_features, n_channels, seed, dgi_epochs, batch_size)
            model = train_classifier(model, train_set, val_set, epochs=epochs, batch_size=batch_size, seed=seed)
            results[kind].append(evaluate(model, make_loader(test_set)))
        pos = test_set.labels().mean()
        print(f"seed {seed}: {len(train_set)}/{len(val_set)}/{len(test_set)} train/val/test sequences, test positive rate {pos:.2f}  ({time.time() - start:.0f}s)")

    table = format_table(results, seeds)
    print()
    print(table)
    print(f"\nTotal time {time.time() - start:.0f}s")
    if out_path:
        write_report(out_path, table, seeds, n_recordings, epochs, dgi_epochs, seq_len, horizon, effect_strength, time.time() - start)
    return results


def format_table(results, seeds) -> str:
    lines = [
        "| Model | Accuracy | F1 | ROC AUC |",
        "|---|---|---|---|",
    ]
    for name, kind in MODELS:
        cells = []
        for metric in ("accuracy", "f1", "auc"):
            vals = np.array([r[metric] for r in results[kind]])
            cells.append(f"{vals.mean():.3f} ± {vals.std():.3f}")
        lines.append(f"| {name} | " + " | ".join(cells) + " |")
    return "\n".join(lines)


def write_report(path, table, seeds, n_recordings, epochs, dgi_epochs, seq_len, horizon, effect_strength, seconds):
    os.makedirs(os.path.dirname(path) or ".", exist_ok=True)
    with open(path, "w") as f:
        f.write(
            "# Ablation on SYNTHETIC data (smoke test)\n\n"
            "**These numbers come from synthetic EEG generated by `seizure_gnn.data.SyntheticEEG`. "
            "They show that the pipeline runs end to end and that each model can learn a deliberately "
            "learnable toy task. They are not research results and are not comparable to the poster's "
            "mid-70% accuracy, which was measured on a real EEG dataset with the original code.**\n\n"
            f"Generated by `python scripts/run_ablation.py` (CPU, {seconds:.0f} s).\n\n"
            "Setup: "
            f"{n_recordings} synthetic recordings of 120 s, 16 channels at 128 Hz, 2 seizures each, "
            f"effect_strength={effect_strength}; "
            "2 s windows with 1 s stride; edges = 0.5 |Pearson| + 0.5 normalized MI, top-4 neighbors; "
            f"sequences of T={seq_len} windows labeled by window t+{horizon} (next-window prediction); "
            "split by recording 60/20/20; "
            f"{dgi_epochs} DGI epochs, {epochs} supervised epochs, best epoch chosen by validation AUC. "
            f"Mean ± std over seeds {list(seeds)} (each seed regenerates the data and the split).\n\n"
            f"{table}\n\n"
            "## How to read this\n\n"
            "* Every model is near the ceiling, because the synthetic seizures (amplitude jump plus a "
            "shared 3-8 Hz rhythm) are easy to see. The gaps between rows are mostly within one or two "
            "standard deviations over only three seeds, so this table does **not** show that fusion "
            "beats the baselines. Ranking the models needs real EEG.\n"
            "* Accuracy and F1 use a fixed 0.5 threshold while the checkpoint is picked by validation "
            "AUC, and the loss is class-weighted, so a model can rank windows well (high AUC) yet be "
            "poorly calibrated at 0.5. In a harder run (`--effect-strength 0.2`, seed 0) the DGI fusion "
            "model had AUC 0.985 but accuracy 0.51 for this reason. Tuning the threshold on validation "
            "data is a planned improvement.\n"
        )
    print(f"Wrote {path}")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--seeds", type=int, nargs="+", default=[0, 1, 2])
    parser.add_argument("--recordings", type=int, default=12)
    parser.add_argument("--epochs", type=int, default=10)
    parser.add_argument("--dgi-epochs", type=int, default=5)
    parser.add_argument("--effect-strength", type=float, default=0.5, help="synthetic seizure strength; lower is harder")
    parser.add_argument("--out", default="results/ablation_synthetic.md")
    args = parser.parse_args()
    run(tuple(args.seeds), args.recordings, args.epochs, args.dgi_epochs, effect_strength=args.effect_strength, out_path=args.out)


if __name__ == "__main__":
    main()
